"""Generate firmware/src/bigfont.h: 1-bit XBM glyphs of a TTF at sizes
larger than U8g2 ships (logisoso tops out at 92 px digits / 58 px letters).

Each size is given as the cap height of the digit '0' in pixels.

  uv run tools/gen_bigfont.py path/to/Logisoso.ttf > firmware/src/bigfont.h

Logisoso (Mathieu Gabiot) is GPL v2 with font exception; it is the
family U8g2's logisoso* fonts come from, so the big numbers match the rest
of the UI.
"""

import sys

from PIL import Image, ImageDraw, ImageFont

CHARS = "0123456789.,-KMB"
# Digits and the K/M/B unit (drawn smaller, sharing the baseline).
SIZES = [("big_130", 130), ("big_110", 110),
         ("unit_78", 78), ("unit_66", 66)]
TRACKING = 0.09  # gap between glyphs, as a fraction of the cap height


def font_for_cap(path: str, cap: int) -> ImageFont.FreeTypeFont:
    # Find the point size whose '0' is `cap` px tall.
    size = cap
    for _ in range(40):
        f = ImageFont.truetype(path, size)
        l, t, r, b = f.getbbox("0", anchor="ls")
        h = b - t
        if h == cap:
            return f
        size = max(1, round(size * cap / h)) if abs(h - cap) > 1 else size + (1 if h < cap else -1)
    return f


def glyph(f: ImageFont.FreeTypeFont, ch: str, cap: int):
    """Logisoso digits are tabular with wide side bearings; crop each glyph
    to its ink and space them proportionally with a fixed tracking."""
    l, t, r, b = f.getbbox(ch, anchor="ls")
    full = Image.new("L", (r - l, b - t), 0)
    ImageDraw.Draw(full).text((-l, -t), ch, font=f, fill=255, anchor="ls")
    il, it, ir, ib = full.getbbox()
    img = full.crop((il, it, ir, ib))
    w, h = img.size
    t = t + it  # bitmap top relative to the baseline
    l = 0
    stride = (w + 7) // 8
    bits = bytearray(stride * h)
    px = img.load()
    for y in range(h):
        for x in range(w):
            if px[x, y] >= 128:
                bits[y * stride + x // 8] |= 1 << (x % 8)  # XBM: LSB first
    return l, t, w, h, w + round(cap * TRACKING), bytes(bits)


def main() -> None:
    path = sys.argv[1]
    out = [
        "// Generated by tools/gen_bigfont.py from Logisoso.ttf (Mathieu Gabiot,",
        "// GPL v2 with font exception). Do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "struct BigGlyph {",
        "  char c;",
        "  int8_t dx;       // bitmap left relative to the pen",
        "  int16_t dy;      // bitmap top relative to the baseline (negative = up)",
        "  uint8_t w, h;",
        "  uint8_t adv;     // pen advance",
        "  const uint8_t *bits;  // XBM, rows of ceil(w/8) bytes, LSB first",
        "};",
        "",
        "struct BigFont {",
        "  uint8_t cap;     // cap height of '0' in px",
        "  uint8_t n;",
        "  const BigGlyph *glyphs;",
        "};",
        "",
    ]
    for name, cap in SIZES:
        f = font_for_cap(path, cap)
        entries = []
        for i, ch in enumerate(CHARS):
            l, t, w, h, adv, bits = glyph(f, ch, cap)
            sym = f"{name}_{i}"
            body = ",".join(f"0x{b:02x}" for b in bits)
            out.append(f"static const uint8_t {sym}[] = {{{body}}};")
            entries.append(f"  {{'{ch}', {l}, {t}, {w}, {h}, {adv}, {sym}}},")
        out.append(f"static const BigGlyph {name}_glyphs[] = {{")
        out.extend(entries)
        out.append("};")
        out.append(f"static const BigFont {name} = {{{cap}, {len(CHARS)}, {name}_glyphs}};")
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
